-- ---------------------------------------------------------------------------
-- LOUELLA BAKERY — Branch equipment seed (branch C2, from Oct30-Nov13-2026.xlsx)
--
-- Needs migration 20261115100000_product_equipment (Product."isEquipment").
-- Run AFTER the four oct2026 files (seed-products/-price-history/-aliases/
-- -inventory). Re-runnable.
--
-- The paper sheet keeps the branch's equipment on page 4 of the pricelist and
-- re-copies its count every day. The workbook seeds skipped those rows; this
-- adds them back as equipment (Miscellaneous, "isEquipment" = true):
--
--   * Product rows for the ten items at the pricelist's values. An item that
--     already exists by name is turned into equipment, not duplicated.
--   * An opening price-history row on 2026-10-29 (the catalog's opening day).
--   * C2 counts 2026-10-31 .. 2026-11-09, counted, exactly as the day sheets
--     say (the same days seed-inventory-oct2026.sql covers). The six items the
--     sheets count never changed: Plancha 61, Trays 51, Thongs 5, Ref 2,
--     Estante 3, Cake Chiller (C2) 1. The other four are blank at C2 (0).
--   * 2026-11-10 .. today (Manila): the count carried, uncounted — the same
--     row autofill writes — so every day since has it. Existing rows are left
--     alone.
--
-- NOTE: seed-inventory-oct2026.sql checks for exactly 1700 C2 rows on its
-- days. After this file there are 1760, so re-running that file alone will
-- fail its check; run this one again after it.
-- ---------------------------------------------------------------------------

BEGIN;

DO $$
DECLARE n int;
BEGIN
  SELECT COUNT(*) INTO n FROM "Branch" WHERE name = 'C2' AND "deletedAt" IS NULL;
  IF n <> 1 THEN
    RAISE EXCEPTION 'expected exactly one live branch named C2, found %', n;
  END IF;
END $$;

CREATE TEMP TABLE equipment (ord int, name text, price numeric, c2_count int) ON COMMIT DROP;
INSERT INTO equipment VALUES
  (1,  'Plancha',              130.00, 61),
  (2,  'Trays',                130.00, 51),
  (3,  'Thongs',                40.00,  5),
  (4,  'Ref',                20000.00,  2),
  (5,  'Estante',            30000.00,  3),
  (6,  'Freezer',            20000.00,  0),
  (7,  'Cake Chiller (C2)',  90000.00,  1),
  (8,  'Wooden Estante/Cab', 10000.00,  0),
  (9,  'Ref-type Chiller',   25000.00,  0),
  (10, 'Board Stand',           10.00,  0);

-- Existing by name: make it equipment under Miscellaneous.
UPDATE "Product" p
SET "isEquipment" = true, type = 'MISCELLANEOUS'
FROM equipment e
WHERE p.name = e.name AND p."deletedAt" IS NULL;

-- New: after the last Miscellaneous item, in pricelist order.
INSERT INTO "Product" (name, type, "sortOrder", price, "isActive", "isEquipment", date, "createdAt")
SELECT e.name, 'MISCELLANEOUS',
       (SELECT COALESCE(MAX("sortOrder"), 0) FROM "Product" WHERE type = 'MISCELLANEOUS') + e.ord,
       e.price, true, true, DATE '2026-10-29', NOW()
FROM equipment e
WHERE NOT EXISTS (SELECT 1 FROM "Product" p WHERE p.name = e.name AND p."deletedAt" IS NULL)
ORDER BY e.ord;

INSERT INTO "ProductPriceHistory" ("productId", price, "effectiveAt", "createdAt")
SELECT p.id, e.price, DATE '2026-10-29', NOW()
FROM equipment e
JOIN "Product" p ON p.name = e.name AND p."deletedAt" IS NULL
WHERE NOT EXISTS (SELECT 1 FROM "ProductPriceHistory" h WHERE h."productId" = p.id);

-- Counted days, as written on the sheets.
INSERT INTO "Inventory"
  ("branchId", "productId", date, quantity, delivery, leftover, reject,
   "isAutoGenerated", "leftoverCountedAt", "createdAt", "updatedAt")
SELECT b.id, p.id, d::date, e.c2_count, 0, e.c2_count, 0, false, NOW(), NOW(), NOW()
FROM equipment e
JOIN "Product" p ON p.name = e.name AND p."deletedAt" IS NULL
CROSS JOIN (SELECT id FROM "Branch" WHERE name = 'C2' AND "deletedAt" IS NULL) b
CROSS JOIN generate_series(DATE '2026-10-31', DATE '2026-11-09', INTERVAL '1 day') d
ON CONFLICT ("branchId", "productId", date) DO UPDATE SET
  quantity            = EXCLUDED.quantity,
  delivery            = 0,
  leftover            = EXCLUDED.leftover,
  reject              = 0,
  "isAutoGenerated"   = false,
  "leftoverCountedAt" = EXCLUDED."leftoverCountedAt",
  "deletedAt"         = NULL,
  "updatedAt"         = NOW();

-- Since then: carried, not counted (what autofill writes). Never overwrites.
INSERT INTO "Inventory"
  ("branchId", "productId", date, quantity, delivery, leftover, reject,
   "isAutoGenerated", "leftoverCountedAt", notes, "createdAt", "updatedAt")
SELECT b.id, p.id, d::date, e.c2_count, 0, e.c2_count, 0, true, NULL,
       'Auto-generated: equipment count carried from 2026-11-09', NOW(), NOW()
FROM equipment e
JOIN "Product" p ON p.name = e.name AND p."deletedAt" IS NULL
CROSS JOIN (SELECT id FROM "Branch" WHERE name = 'C2' AND "deletedAt" IS NULL) b
CROSS JOIN generate_series(DATE '2026-11-10', (NOW() AT TIME ZONE 'Asia/Manila')::date, INTERVAL '1 day') d
ON CONFLICT ("branchId", "productId", date) DO NOTHING;

DO $$
DECLARE n int;
BEGIN
  SELECT COUNT(*) INTO n FROM "Product" WHERE "isEquipment" AND "deletedAt" IS NULL;
  IF n < 10 THEN
    RAISE EXCEPTION 'expected the 10 equipment products, found %', n;
  END IF;
  SELECT COUNT(*) INTO n
  FROM "Inventory" i
  JOIN "Branch" b ON b.id = i."branchId"
  JOIN "Product" p ON p.id = i."productId"
  WHERE b.name = 'C2' AND p."isEquipment" AND i."deletedAt" IS NULL
    AND i.date BETWEEN DATE '2026-10-31' AND DATE '2026-11-09'
    AND i."leftoverCountedAt" IS NOT NULL;
  IF n <> 100 THEN
    RAISE EXCEPTION 'expected 100 counted C2 equipment rows 2026-10-31..2026-11-09, found %', n;
  END IF;
END $$;

COMMIT;
