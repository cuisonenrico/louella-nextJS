-- Owns: ProductPriceHistory. Run AFTER seed-products-apr2026.sql.
--
-- HOW THIS IS BUILT
--   Every day sheet in the archive is read in chronological order, and a row
--   is written the day a product's price first DIFFERS from its previous
--   price. So the history records when each change actually took effect,
--   including changes that happen part-way through a fortnight — a
--   once-per-workbook snapshot would miss those and the affected sheets would
--   refuse to import.
--
--   Prices that merely repeat are not re-recorded, so the row count reflects
--   real changes rather than observations.
--
-- WHY THIS IS REQUIRED, not optional:
--   1. The importer identifies same-named products by price AS OF the sheet's
--      date. Without history every sheet is compared against today's
--      Product.price, so any older workbook refuses with "matches none".
--   2. computeSold/revenue value historical rows through getEffectivePrice().
--      Without history, the whole archive is priced at today's rates.
--
-- MAPPING ASSUMPTION — only bears on the duplicated names:
--   Within a sheet, the Nth occurrence of a name is taken to be the Nth
--   product carrying that name in seed-products-apr2026.sql (ordered by id).
--   Position is the only signal that survives a repricing: price itself cannot
--   link January's "Bonette @5" to April's "Bonette @8", because the price is
--   exactly what changed.
--
-- Coverage: 336 rows, 169 products, 29 distinct effective dates
-- (2025-12-31 .. 2026-05-13). 117 products changed price at least once.
