  // ─────────────────────────────────────────────────────────────────────────
  // updateBulk
  //
  // The sheet used to PATCH one row per edit through Promise.all. Against the
  // global 20-request/minute throttle, editing a 165-product sheet 429s after
  // the twentieth row — and Promise.all rejects on the first failure, so the
  // user gets "save failed" on a partial write. One request, one transaction.
  // ─────────────────────────────────────────────────────────────────────────

  // ─────────────────────────────────────────────────────────────────────────
  // Impossible rows
  //
  // Nothing stopped leftover + reject exceeding the stock that existed, so a
  // typo produced negative `sold` and negative revenue. `zeroSales` filters
  // `sold <= 0`, which quietly absorbed it instead of surfacing it.
  // ─────────────────────────────────────────────────────────────────────────

  // ─────────────────────────────────────────────────────────────────────────
  // Audit trail
  //
  // createdById answered "who entered this"; nothing answered "who changed it".
  // Edits move revenue, so they are exactly the writes worth attributing.
  // ─────────────────────────────────────────────────────────────────────────

  describe('audit trail', () => {
    it('records who amended a row', async () => {
      prisma.inventory.findFirst.mockResolvedValue(makeInvRow());
      prisma.inventory.update.mockResolvedValue(makeInvRow());
      prisma.inventory.count.mockResolvedValue(0);

      await service.update(1, { delivery: 5 }, undefined, 42);

      expect(prisma.inventory.update.mock.calls[0][0].data.updatedById).toBe(42);
    });

    it('records who amended each row of a bulk save', async () => {
      prisma.inventory.findMany
        .mockResolvedValueOnce([makeInvRow({ id: 1 }), makeInvRow({ id: 2 })])
        .mockResolvedValueOnce([]);
      prisma.$transaction.mockResolvedValue([]);

      await service.updateBulk([{ id: 1, delivery: 5 }, { id: 2, delivery: 6 }], undefined, 42);

      for (const call of prisma.inventory.update.mock.calls) {
        expect(call[0].data.updatedById).toBe(42);
      }
    });

    it('leaves the attribution null when there is no authenticated user', async () => {
      prisma.inventory.findFirst.mockResolvedValue(makeInvRow());
      prisma.inventory.update.mockResolvedValue(makeInvRow());
      prisma.inventory.count.mockResolvedValue(0);

      await service.update(1, { delivery: 5 });

      expect(prisma.inventory.update.mock.calls[0][0].data.updatedById).toBeNull();
    });
  });

  describe('impossible rows', () => {
    it('refuses an update whose leftover exceeds the stock on hand', async () => {
      prisma.inventory.findFirst.mockResolvedValue(
        makeInvRow({ quantity: 100, delivery: 0, leftover: 10, reject: 0 }),
      );

      await expect(
        service.update(1, { leftover: 500 }),
      ).rejects.toBeInstanceOf(BadRequestException);
      expect(prisma.inventory.update).not.toHaveBeenCalled();
    });

    it('refuses when leftover and reject together exceed the stock', async () => {
      prisma.inventory.findFirst.mockResolvedValue(
        makeInvRow({ quantity: 100, delivery: 0, leftover: 0, reject: 0 }),
      );

      await expect(
        service.update(1, { leftover: 60, reject: 60 }),
      ).rejects.toBeInstanceOf(BadRequestException);
    });

    it('counts adjustments as part of the stock on hand', async () => {
      // 100 opening + 50 pulled in leaves room for a 140 leftover.
      prisma.inventory.findFirst.mockResolvedValue(
        makeInvRow({
          quantity: 100,
          delivery: 0,
          leftover: 0,
          reject: 0,
          adjustments: [{ type: 'PULL_IN', value: 50 }],
        }),
      );
      prisma.inventory.update.mockResolvedValue(makeInvRow({ leftover: 140 }));
      prisma.inventory.findMany.mockResolvedValue([]); // nothing downstream to cascade
      prisma.inventory.count.mockResolvedValue(0);

      await expect(service.update(1, { leftover: 140 })).resolves.toBeDefined();
    });

    it('allows a row that sells out exactly', async () => {
      prisma.inventory.findFirst.mockResolvedValue(
        makeInvRow({ quantity: 100, delivery: 0, leftover: 0, reject: 0 }),
      );
      prisma.inventory.update.mockResolvedValue(makeInvRow({ leftover: 100 }));
      prisma.inventory.findMany.mockResolvedValue([]);
      prisma.inventory.count.mockResolvedValue(0);

      await expect(service.update(1, { leftover: 100 })).resolves.toBeDefined();
    });

    it('refuses an impossible row inside a bulk save', async () => {
      prisma.inventory.findMany.mockResolvedValueOnce([
        makeInvRow({ id: 1, quantity: 10, delivery: 0, leftover: 0, reject: 0 }),
      ]);

      await expect(
        service.updateBulk([{ id: 1, leftover: 500 }]),
      ).rejects.toBeInstanceOf(BadRequestException);
      expect(prisma.$transaction).not.toHaveBeenCalled();
    });
  });

  describe('updateBulk', () => {
    const rowsFor = (ids: number[]) =>
      ids.map((id) =>
        makeInvRow({ id, productId: id, leftover: 20, isAutoGenerated: false }),
      );

    it('writes every edit in a single transaction', async () => {
      prisma.inventory.findMany
        .mockResolvedValueOnce(rowsFor([1, 2, 3]))
        .mockResolvedValueOnce([]); // no downstream rows to carry or warn about
      prisma.$transaction.mockResolvedValue([]);

      const res = await service.updateBulk([
        { id: 1, delivery: 5 },
        { id: 2, delivery: 6 },
        { id: 3, delivery: 7 },
      ]);

      expect(res.updated).toBe(3);
      expect(prisma.$transaction).toHaveBeenCalledTimes(1);
      expect(prisma.inventory.update).toHaveBeenCalledTimes(3);
    });

    it('refuses the whole batch when a row is outside the branch scope', async () => {
      // Only two of the three ids come back once the scope is applied.
      prisma.inventory.findMany.mockResolvedValueOnce(rowsFor([1, 2]));

      await expect(
        service.updateBulk(
          [{ id: 1, delivery: 5 }, { id: 2, delivery: 6 }, { id: 3, delivery: 7 }],
          1,
        ),
      ).rejects.toBeInstanceOf(NotFoundException);
      expect(prisma.$transaction).not.toHaveBeenCalled();
    });

    it('scopes its lookup to the branch when one is given', async () => {
      prisma.inventory.findMany
        .mockResolvedValueOnce(rowsFor([1]))
        .mockResolvedValueOnce([]);
      prisma.$transaction.mockResolvedValue([]);

      await service.updateBulk([{ id: 1, delivery: 5 }], 7);

      const where = prisma.inventory.findMany.mock.calls[0][0].where;
      expect(where).toMatchObject({ branchId: 7, deletedAt: null });
    });

    it('cascades downstream auto rows when a leftover changes', async () => {
      prisma.inventory.findMany
        .mockResolvedValueOnce(rowsFor([1])) // the rows being edited
        .mockResolvedValueOnce([
          // downstream rows for product 1, ascending by date
          { id: 90, branchId: 1, productId: 1, date: new Date('2024-01-02'), isAutoGenerated: true, delivery: 0, adjustments: [] },
          { id: 91, branchId: 1, productId: 1, date: new Date('2024-01-03'), isAutoGenerated: true, delivery: 0, adjustments: [] },
          { id: 92, branchId: 1, productId: 1, date: new Date('2024-01-04'), isAutoGenerated: false, delivery: 0, adjustments: [] },
        ]);
      prisma.$transaction.mockResolvedValue([]);

      const res = await service.updateBulk([{ id: 1, leftover: 9 }]);

      // Stops at the manual row, exactly as recascadeLeftovers does.
      expect(res.cascadeUpdated).toBe(2);
      const cascaded = prisma.inventory.update.mock.calls
        .map((c) => c[0])
        .filter((c) => c.where.id === 90 || c.where.id === 91);
      expect(cascaded).toEqual([
        expect.objectContaining({ where: { id: 90 }, data: { quantity: 9, leftover: 9 } }),
        expect.objectContaining({ where: { id: 91 }, data: { quantity: 9, leftover: 9 } }),
      ]);
    });

    it('warns about stale downstream rows when leftover was not touched', async () => {
      // Editing only delivery leaves later placeholder days derived from an
      // older leftover. The single-row update() surfaced that as
      // cascadeWarning; the bulk path has to keep telling the user.
      prisma.inventory.findMany
        .mockResolvedValueOnce(rowsFor([1]))
        .mockResolvedValueOnce([
          { id: 90, branchId: 1, productId: 1, date: new Date('2024-01-02'), isAutoGenerated: true, delivery: 0, adjustments: [] },
        ]);
      prisma.$transaction.mockResolvedValue([]);

      const res = await service.updateBulk([{ id: 1, delivery: 5 }]);

      expect(res.cascadeUpdated).toBe(0);
      expect(res.cascadeWarnings).toEqual([
        { branchId: 1, productId: 1, fromDate: '2024-01-01' },
      ]);
    });

    it('does not warn about a row it already cascaded', async () => {
      prisma.inventory.findMany
        .mockResolvedValueOnce(rowsFor([1]))
        .mockResolvedValueOnce([
          { id: 90, branchId: 1, productId: 1, date: new Date('2024-01-02'), isAutoGenerated: true, delivery: 0, adjustments: [] },
        ]);
      prisma.$transaction.mockResolvedValue([]);

      const res = await service.updateBulk([{ id: 1, leftover: 9 }]);

      expect(res.cascadeUpdated).toBe(1);
      expect(res.cascadeWarnings).toEqual([]);
    });

    it('carries a placeholder delivery forward in the bulk cascade too', async () => {
      prisma.inventory.findMany
        .mockResolvedValueOnce(rowsFor([1]))
        .mockResolvedValueOnce([
          { id: 90, branchId: 1, productId: 1, date: new Date('2024-01-02'), isAutoGenerated: true, delivery: 12, adjustments: [] },
          { id: 91, branchId: 1, productId: 1, date: new Date('2024-01-03'), isAutoGenerated: true, delivery: 0, adjustments: [] },
        ]);
      prisma.$transaction.mockResolvedValue([]);

      const res = await service.updateBulk([{ id: 1, leftover: 9 }]);

      expect(res.cascadeUpdated).toBe(2);
      const written = prisma.inventory.update.mock.calls
        .map((c) => c[0])
        .filter((c) => c.where.id === 90 || c.where.id === 91);
      expect(written).toEqual([
        expect.objectContaining({ where: { id: 90 }, data: { quantity: 9, leftover: 21 } }),
        expect.objectContaining({ where: { id: 91 }, data: { quantity: 21, leftover: 21 } }),
      ]);
    });

    it('does not cascade when no leftover changed', async () => {
      prisma.inventory.findMany
        .mockResolvedValueOnce(rowsFor([1]))
        .mockResolvedValueOnce([]);
      prisma.$transaction.mockResolvedValue([]);

      const res = await service.updateBulk([{ id: 1, delivery: 5 }]);

      expect(res.cascadeUpdated).toBe(0);
      expect(res.cascadeWarnings).toEqual([]);
    });
  });

  describe('aggregation caching', () => {
    it('getSummary computes once, then serves from cache for identical args', async () => {
      prisma.inventory.findMany.mockResolvedValue([]);

      await service.getSummary(1, '2024-01-01', '2024-01-01');
      await service.getSummary(1, '2024-01-01', '2024-01-01');

      expect(prisma.inventory.findMany).toHaveBeenCalledTimes(1);
    });

    it('getSummary recomputes after the inventory namespace is bumped', async () => {
      prisma.inventory.findMany.mockResolvedValue([]);

      await service.getSummary(1, '2024-01-01', '2024-01-01');
      cache.bump('inventory-agg');
      await service.getSummary(1, '2024-01-01', '2024-01-01');

      expect(prisma.inventory.findMany).toHaveBeenCalledTimes(2);
    });

    it('getSummary caches per-branch/date (different args miss separately)', async () => {
      prisma.inventory.findMany.mockResolvedValue([]);

      await service.getSummary(1, '2024-01-01', '2024-01-01');
      await service.getSummary(2, '2024-01-01', '2024-01-01');

      expect(prisma.inventory.findMany).toHaveBeenCalledTimes(2);
    });
  });
