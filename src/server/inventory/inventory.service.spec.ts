function makeInvRow(
  overrides: Partial<{
    id: number;
    branchId: number;
    productId: number;
    date: Date;
    quantity: number;
    delivery: number;
    leftover: number;
    reject: number;
    isAutoGenerated: boolean;
    adjustments: { type: string; value: number }[];
    product: { id: number; type: string; price: number; name: string };
  }> = {},
) {
  return {
    id: 1,
    branchId: 1,
    productId: 1,
    date: new Date('2024-01-01'),
    quantity: 100,
    delivery: 0,
    leftover: 20,
    reject: 0,
    isAutoGenerated: true,
    adjustments: [],
    product: { id: 1, type: 'BREAD', price: 10, name: 'Pandesal' },
    ...overrides,
  };
}

function makeCache() {
  const store = new Map<string, unknown>();
  return {
    store,
    wrap: jest.fn(
      async (
        ns: string,
        parts: (string | number)[],
        fn: () => Promise<unknown>,
      ) => {
        const key = `${ns}:${parts.join(':')}`;
        if (store.has(key)) return store.get(key);
        const val = await fn();
        store.set(key, val);
        return val;
      },
    ),
    bump: jest.fn((ns: string) => {
      for (const k of [...store.keys()])
        if (k.startsWith(`${ns}:`)) store.delete(k);
    }),
  };
}

